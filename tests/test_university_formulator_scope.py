@pytest.mark.parametrize('index', [0, 1])
def test_both_recorded_workflow_intent_failures_remain_rejected_and_unchanged(index):
    case = FIXTURE['cases'][index]; original = deepcopy(case['response'])
    assert FormulatorResponse.model_validate(original)
    result = convert_formulation(original, case['source_ref_to_text'])
    assert result['problem'] is None and result['unsupported_features']
    assert result['unsupported_features'][0]['kind'] == original['unsupported_features'][0]['kind']
    assert value_hash(original) == case['response_canonical_sha256']
    assert original == case['response']  # No production filtering/auto-acceptance was added.


@pytest.mark.parametrize('index', [0, 1])
def test_explicit_offline_corrected_copy_proves_valid_math_not_live_model_success(index):
    case = FIXTURE['cases'][index]; original = deepcopy(case['response']); copied = deepcopy(original)
    copied['unsupported_features'] = []  # Test-only hypothetical correction, never applied to stored output.
    result = convert_formulation(copied, case['source_ref_to_text'])
    problem = ProblemInput.model_validate(result['problem'])
    assert not result['unsupported_features'] and not result['missing_fields'] and not result['ambiguities']
    assert problem.objective.sense == 'minimize'
    assert problem.objective.source.expression == '(1-x1)**2 + 100*(x2-x1**2)**2'
    assert [(v.name, v.type, v.lower, v.upper) for v in problem.variables] == [('x1', 'real', -2.0, 2.0), ('x2', 'real', -1.0, 3.0)]
    assert original == case['response'] and value_hash(original) == case['response_canonical_sha256']


def test_prompt_revision_preserves_legacy_and_explicitly_separates_workflow_intent():
    old = (PROMPTS / 'formulator.v1.txt').read_bytes()
    assert sha256(old).hexdigest() == FIXTURE['legacy_prompt_file_sha256']
    modern = (PROMPTS / 'formulator.v1.1.txt').read_text()
    assert modern.startswith(old.decode('utf-8'))
    for rule in ('ONLY mathematical properties', 'valid WORKFLOW INTENT', 'unsupported_features=[]',
                 'solver_selection_and_execution', 'روش‌شناسی و اجرای حل', 'integer/discrete', 'general constraints',
                 'Missing or contradictory bounds', 'never invent bounds'):
        assert rule in modern
    assert 'formulator.v1' in freeze_prompt_bundle() and 'formulator.v1.1' in freeze_prompt_bundle()


@pytest.mark.parametrize('mode', ['json_schema', 'json_object', 'text_json'])
def test_wire_prompt_and_provenance_agree_while_output_protocol_and_caps_stay(mode):
    case = FIXTURE['cases'][0]
    ctx = FormulatorContext.model_validate({'sources': [{'source_ref': ref, 'text': text} for ref, text in case['source_ref_to_text'].items()]})
    profile = snapshot().model_copy(update={'response_mode': mode})
    prepared = prepare_provider_request(profile, 'formulator.v1', ctx)
    body = prepared.request
    assert prepared.provenance['schema_id'] == 'formulator.v1'
    assert prepared.provenance['prompt_name'] == 'formulator.v1.1' and prepared.provenance['prompt_version'] == '1.1'
    assert body[profile.token_limit_field] == profile.max_output_tokens
    assert prepared.provenance['effective_max_output_tokens'] == profile.max_output_tokens
    assert sha256(body['messages'][0]['content'].encode('utf-8')).hexdigest() == prepared.provenance['system_message_sha256']
    assert body == build_request(profile, 'formulator.v1', ctx.model_dump(mode='json', exclude_none=True))
    assert body['messages'][0]['content'].startswith((PROMPTS / 'formulator.v1.1.txt').read_text().strip())
    assert prepared.response_schema == provider_schema(FormulatorResponse)
    if mode == 'json_schema': assert body['response_format']['json_schema']['name'] == 'formulator_v1'


@pytest.mark.parametrize('case', ['integer', 'general_constraint', 'missing_bound'])
def test_genuine_mathematical_restrictions_and_missing_bounds_are_preserved(case):
    source = FIXTURE['cases'][0]; response = deepcopy(source['response']); response['unsupported_features'] = []
    sources = deepcopy(source['source_ref_to_text'])
    if case == 'integer':
        sentence = 'x1 صحیح است.'; sources['input:text'] += '\n' + sentence
        response['extracted_fields']['variables'][0]['type'] = 'integer'
        next(e for e in response['source_map'] if e['field_path'] == '/variables/0/type')['quote'] = sentence
    elif case == 'general_constraint':
        sentence = 'قید عمومی x1+x2 <= 1 برقرار است.'; sources['input:text'] += '\n' + sentence
        response['extracted_fields']['constraints'] = [{'source_text': sentence, 'expression': 'x1+x2 <= 1'}]
        response['source_map'].append({'field_path': '/constraints/0/source_text', 'source_ref': 'input:text', 'quote': sentence})
    else:
        response['extracted_fields']['variables'][0]['lower'] = None
        response['source_map'] = [e for e in response['source_map'] if e['field_path'] != '/variables/0/lower']
    result = convert_formulation(response, sources)
    assert result['problem'] is None
    if case == 'integer': assert any(f['kind'] == 'non_real' for f in result['unsupported_features'])
    elif case == 'general_constraint': assert any(f['kind'] == 'constraint' for f in result['unsupported_features'])
    else:
        assert '/variables/0/lower' in result['missing_fields']
        assert any(q['field_path'] == '/variables/0/lower' for q in result['ambiguities'])
        assert not result['unsupported_features']
